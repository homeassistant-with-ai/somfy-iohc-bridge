// Host-native test (no ESP32/hardware needed):
//   g++ -std=c++17 -I ../lib/iohc -o /tmp/test_crc test_crc.cpp && /tmp/test_crc
#include "../lib/iohc/iohc_crc.h"
#include <cstdio>

int main() {
  // Test vectors from iown-home docs/radio.md "CRC example"
  const uint8_t v1[] = {0xF8,0x00,0x00,0x00,0x3F,0x1A,0x38,0x0B,0x00,0x01,0x61,0x00,0x00,0x80,0xD8,0x05,0x00,0x02,0xA6,0x24,0x22,0x2E,0x8B,0xA3,0x51};
  uint16_t c1 = iohc::crc16(v1, sizeof(v1));
  printf("vector1 crc = %04X (expect 525F) -> %s\n", c1, c1 == 0x525F ? "PASS" : "FAIL");

  const uint8_t v2[] = {0xF8,0x00,0x00,0x00,0x3F,0x1A,0x38,0x0B,0x00,0x01,0x61,0x00,0x00,0x80,0xD8,0x05,0x00,0x02,0xA6,0x24,0x22,0x2E,0x8B,0xA3,0x51,0x5F,0x52};
  uint16_t c2 = iohc::crc16(v2, sizeof(v2));
  printf("vector2 crc = %04X (expect 0000) -> %s\n", c2, c2 == 0x0000 ? "PASS" : "FAIL");

  return (c1 == 0x525F && c2 == 0x0000) ? 0 : 1;
}
